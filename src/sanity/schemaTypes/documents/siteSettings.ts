import { defineArrayMember, defineField, defineType } from 'sanity';

export const siteSettings = defineType({
  name: 'siteSettings',
  title: 'Site settings',
  type: 'document',
  groups: [
    { name: 'identity', title: 'Identity', default: true },
    { name: 'contact', title: 'Contact & availability' },
    { name: 'footer', title: 'Footer' },
    { name: 'newsletter', title: 'Newsletter' },
    { name: 'seo', title: 'Default SEO' },
  ],
  fields: [
    defineField({
      name: 'siteName',
      title: 'Site name',
      type: 'string',
      group: 'identity',
      description: 'Used in page titles, e.g. "Work — madebyfn".',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'studioName',
      title: 'Studio name',
      type: 'string',
      group: 'identity',
      description: 'The wordmark shown in the header and footer.',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'studioDescriptor',
      title: 'Wordmark descriptor',
      type: 'string',
      group: 'identity',
      description: 'Tiny label beside the wordmark, e.g. "Studio".',
    }),
    defineField({
      name: 'legalName',
      title: 'Legal entity name',
      type: 'string',
      group: 'identity',
      description: 'Used in the copyright line, e.g. "madebyfn Ltd."',
    }),
    defineField({
      name: 'siteUrl',
      title: 'Site URL',
      type: 'url',
      group: 'identity',
      description: 'Canonical production URL, without a trailing slash.',
      validation: (rule) => rule.required().uri({ scheme: ['https', 'http'] }),
    }),
    defineField({
      name: 'logo',
      title: 'Logo',
      type: 'imageWithAlt',
      group: 'identity',
      description: 'Optional. When empty the studio name is rendered as a typographic wordmark.',
    }),
    defineField({
      name: 'alternateLogo',
      title: 'Alternate logo',
      type: 'imageWithAlt',
      group: 'identity',
      description: 'Optional light-on-dark variant for the footer.',
    }),
    defineField({
      name: 'favicon',
      title: 'Favicon',
      type: 'image',
      group: 'identity',
      description: 'Square SVG or PNG, at least 512×512.',
    }),
    defineField({
      name: 'establishedYear',
      title: 'Established year',
      type: 'number',
      group: 'identity',
      validation: (rule) => rule.min(1990).max(2100),
    }),

    defineField({
      name: 'primaryEmail',
      title: 'Primary email',
      type: 'string',
      group: 'contact',
      validation: (rule) => rule.required().email(),
    }),
    defineField({ name: 'location', title: 'Location', type: 'string', group: 'contact', description: 'e.g. "London, UK"' }),
    defineField({
      name: 'timezone',
      title: 'Time zone',
      type: 'string',
      group: 'contact',
      description: 'IANA name used for the live clock in the footer, e.g. "Europe/London".',
      initialValue: 'Europe/London',
    }),
    defineField({
      name: 'timezoneLabel',
      title: 'Time zone label',
      type: 'string',
      group: 'contact',
      description: 'Short label shown after the clock, e.g. "GMT".',
    }),
    defineField({
      name: 'availability',
      title: 'Availability',
      type: 'object',
      group: 'contact',
      fields: [
        defineField({
          name: 'status',
          title: 'Status',
          type: 'string',
          options: {
            list: [
              { title: 'Available', value: 'available' },
              { title: 'Limited', value: 'limited' },
              { title: 'Unavailable', value: 'unavailable' },
            ],
            layout: 'radio',
            direction: 'horizontal',
          },
          initialValue: 'available',
          validation: (rule) => rule.required(),
        }),
        defineField({ name: 'label', title: 'Short label', type: 'string', description: 'e.g. "Available"', validation: (rule) => rule.required() }),
        defineField({ name: 'detail', title: 'Detail', type: 'string', description: 'e.g. "Taking on new projects from Q1 2025"' }),
        defineField({ name: 'menuLabel', title: 'Mobile menu label', type: 'string', description: 'e.g. "Available for Q1 2025"' }),
        defineField({ name: 'responseTime', title: 'Response time', type: 'string', description: 'e.g. "Within 48 hours, usually sooner"' }),
      ],
    }),
    defineField({
      name: 'socialLinks',
      title: 'Social links',
      type: 'array',
      group: 'contact',
      of: [defineArrayMember({ type: 'socialLink' })],
    }),

    defineField({
      name: 'footerDescription',
      title: 'Footer description',
      type: 'text',
      rows: 3,
      group: 'footer',
      description: 'Short studio description under the wordmark.',
    }),
    defineField({
      name: 'footerNavigationLabel',
      title: 'Navigation column label',
      type: 'string',
      group: 'footer',
      initialValue: 'Navigation',
    }),
    defineField({
      name: 'footerDevelopersLabel',
      title: 'Developers column label',
      type: 'string',
      group: 'footer',
      initialValue: 'Developers',
    }),
    defineField({
      name: 'footerStatusLabel',
      title: 'Status column label',
      type: 'string',
      group: 'footer',
      initialValue: 'Status',
    }),
    defineField({
      name: 'copyrightNote',
      title: 'Copyright note',
      type: 'string',
      group: 'footer',
      description: 'Appended after the year and legal name, e.g. "All rights reserved."',
    }),

    defineField({
      name: 'newsletter',
      title: 'Newsletter',
      type: 'object',
      group: 'newsletter',
      fields: [
        defineField({ name: 'enabled', title: 'Show newsletter signup', type: 'boolean', initialValue: true }),
        defineField({ name: 'heading', title: 'Heading', type: 'string', validation: (rule) => rule.required() }),
        defineField({ name: 'copy', title: 'Supporting copy', type: 'text', rows: 2 }),
        defineField({ name: 'placeholder', title: 'Input placeholder', type: 'string', initialValue: 'you@company.com' }),
        defineField({ name: 'buttonLabel', title: 'Button label', type: 'string', initialValue: 'Subscribe' }),
        defineField({ name: 'successMessage', title: 'Success message', type: 'string', validation: (rule) => rule.required() }),
        defineField({ name: 'duplicateMessage', title: 'Already subscribed message', type: 'string' }),
        defineField({ name: 'privacyNote', title: 'Privacy note', type: 'string', description: 'Tiny reassurance under the form.' }),
      ],
    }),

    defineField({ name: 'defaultSeo', title: 'Default SEO', type: 'seo', group: 'seo' }),
  ],
  preview: {
    prepare: () => ({ title: 'Site settings' }),
  },
});
